<?php

    //while loop
    $i=1;
    while ($i<=10){
        echo $i." ";
        $i++;
    }

    //do-while
    $i=100;
    do{
        $i." ";
        $i--;
    } while ($i>=0);

    //for
    for ($counter=1;$counter<=10;$counter++){
        echo $counter." ";
    }

    //תרגיל כיתה
    //כתבו את לוח הכפל 
    
?>